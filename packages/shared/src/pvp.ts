/**
 * Флаги и карма.
 *
 * Три состояния, и переходы между ними — единственное, что стоит между
 * открытым миром и резнёй без последствий:
 *
 * - **белый** — мирный. Его можно ударить, но за убийство придёт карма;
 * - **фиолетовый** — сам полез. Отвечать ему можно безнаказанно, и это
 *   временно: полез — не значит вне закона навсегда;
 * - **красный** — убийца. Карма висит на нём, пока не сойдёт, и со смертью
 *   он рискует надетым.
 *
 * Числа лежат здесь, а не на сервере, потому что клиент по ним красит ники
 * и должен получать тот же ответ, что и сервер. Решения принимает всё равно
 * сервер: клиент только рисует.
 */

export type PvpFlag = 'white' | 'purple' | 'red';

/** Сколько висит фиолетовый после нападения, секунды. */
export const PURPLE_SECONDS = 60;

/** Карма за убийство мирного. */
export const KARMA_PER_KILL = 100;

/** Сколько кармы сходит за секунду мирной жизни. Сотня — примерно за пять минут. */
export const KARMA_DECAY_PER_SECOND = 100 / 300;

/** Сколько кармы снимает убитый зверь: замаливать делом быстрее, чем ждать. */
export const KARMA_PER_MOB = 8;

/**
 * Шанс уронить надетое при смерти красного.
 *
 * Именно шанс, а не гарантия: наказание должно пугать, а не превращать первую
 * же ошибку в конец персонажа. И не ноль — иначе краснеть ничего не стоит.
 */
export const RED_DROP_CHANCE = 0.5;

/** Сколько опыта навыков теряет красный при смерти, доля. */
export const RED_SKILL_PENALTY = 0.1;

export function flagOf(karma: number, purpleFor: number): PvpFlag {
  if (karma > 0) return 'red';
  return purpleFor > 0 ? 'purple' : 'white';
}

/** Цвет ника. Клиент берёт его отсюда, чтобы не заводить вторую палитру. */
export const FLAG_COLORS: Record<PvpFlag, string> = {
  white: '#d5c9ab',
  purple: '#b48ad8',
  red: '#d06a5c',
};
