/**
 * Часы мира.
 *
 * Время суток обязано быть общим: ночь наступает у всех сразу, иначе
 * разваливается всё, что от неё зависит — видимость, факелы, поведение мобов,
 * а в будущем и вылазки в подземелья.
 *
 * Хозяин времени — сервер, но отдельного поля в снапшоте не понадобилось:
 * в нём уже есть номер тика, а тик у сервера один на всех и идёт с постоянной
 * частотой. Значит время выводится из тика обеими сторонами одинаково, и
 * протокол трогать не нужно.
 */

/** Сколько настоящих секунд длятся игровые сутки. */
export const DAY_SECONDS = 1200;

/**
 * Время суток: 0 — полночь, 0.25 — рассвет, 0.5 — полдень, 0.75 — закат.
 *
 * Мир начинается не с полуночи: первое, что видит новый игрок, — сумеречное
 * утро, ради которого вся картинка и настраивалась.
 */
export const DAY_START = 0.28;

/**
 * `shift` — сдвиг, поставленный ведущим через служебное меню. Складывается
 * со временем, а не заменяет его: часы после перевода стрелок продолжают идти,
 * а не застывают на выбранном часе.
 */
export function timeOfDay(tick: number, tickRate: number, shift = 0): number {
  const seconds = tick / Math.max(tickRate, 1);
  return (((DAY_START + shift + seconds / DAY_SECONDS) % 1) + 1) % 1;
}

/**
 * Высота солнца над горизонтом: −1 в полночь, +1 в полдень.
 *
 * Это не астрономия, а кривая для освещения: важно лишь, что она гладкая,
 * симметрична относительно полудня и проходит через ноль на рассвете и закате.
 */
export function sunHeight(time: number): number {
  return -Math.cos(time * Math.PI * 2);
}

/** Светло ли снаружи. По этому же признаку гаснут и зажигаются фонари. */
export function isDaylight(time: number): boolean {
  return sunHeight(time) > 0;
}
